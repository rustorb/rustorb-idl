"""The C backend: ``rustorb-idl -bc``.

Writes ``<name>.h`` and ``<name>.c`` for ``<name>.idl``, following the OMG
C Language Mapping 1.0:

- scoped names join their parts with ``_`` (``Mod_Iface_op``); enumerators
  and constants are named in the scope of the enum or constant
  (``Mod_RED``) and constants are ``#define``s;
- structs, exceptions and unions are C structs (a union has ``_d`` and the
  union ``_u``); sequences are ``CORBA_sequence_<element>`` with
  ``_maximum``, ``_length`` and ``_buffer``; arrays are C arrays with a
  ``<Name>_slice`` type; strings are ``CORBA_char*``;
- an interface ``Mod::I`` is ``typedef CORBA_Object Mod_I`` with a stub
  function per operation (and those of its bases), ``Mod_I__get_<attr>``
  and ``Mod_I__set_<attr>`` for attributes; the skeleton is ``POA_Mod_I``
  with ``POA_Mod_I__epv``, ``POA_Mod_I__vepv``, ``POA_Mod_I__init`` and
  ``POA_Mod_I__fini``;
- a local interface ``Mod::L`` has the same stubs and ``POA_Mod_L`` structs,
  without activation: ``POA_Mod_L__init`` makes a struct the
  implementation of local objects, which ``Mod_L__create(impl, ev)`` makes
  and whose stubs call it directly (``CORBA_tk_local_interface``; sending
  one is ``MARSHAL`` minor 4);
- parameters are passed as tables 1-2 and 1-3 of the mapping say: the
  variable-length out values and results are allocated by the callee and
  freed with ``CORBA_free``.

What the mapping leaves to the ORB follows the rustorb runtime (``c/`` of
rustorb, MIT OR Apache-2.0): each type has a descriptor ``<Name>__desc``
(its TypeCode parameters and its C layout) that the runtime's generic
reader, writer and freer walk, and ``TC_<Name>``, ``<Name>__alloc()`` and
``CORBA_sequence_<T>_allocbuf()`` use. The source holds the descriptors,
the stubs and the skeletons.

Valuetypes, abstract interfaces, ``int8`` and the IDL 4 bitmask and bitset
have no C mapping and are errors (rustorb#187).
"""

import os
import re

from . import cxx_backend
from . import frontend as fe

HEADER = (
    "/* Generated by rustorb-idl from %s. Do not edit.\n"
    " *\n"
    " * This file is not covered by the license of rustorb-idl. */\n"
)

# C and C++ keywords (the header is also included from C++): IDL names that
# are keywords get a leading "_".
KEYWORDS = set(
    """
    auto break case char const continue default do double else enum extern float for goto
    if inline int long register restrict return short signed sizeof static struct switch
    typedef union unsigned void volatile while _Bool _Complex _Imaginary
    alignas alignof and and_eq asm bitand bitor bool catch char16_t char32_t class compl
    concept consteval constexpr constinit const_cast co_await co_return co_yield decltype
    delete dynamic_cast explicit export false friend mutable namespace new noexcept not
    not_eq nullptr operator or or_eq private protected public reinterpret_cast requires
    static_assert static_cast template this thread_local throw true try typeid typename
    using virtual wchar_t xor xor_eq
    """.split()
)

BASIC = {
    "boolean": "CORBA_boolean",
    "octet": "CORBA_octet",
    "char": "CORBA_char",
    "wchar": "CORBA_wchar",
    "short": "CORBA_short",
    "ushort": "CORBA_unsigned_short",
    "long": "CORBA_long",
    "ulong": "CORBA_unsigned_long",
    "longlong": "CORBA_long_long",
    "ulonglong": "CORBA_unsigned_long_long",
    "float": "CORBA_float",
    "double": "CORBA_double",
    "longdouble": "CORBA_long_double",
}

# The names of element types in CORBA_sequence_<name> (1.11).
SEQ_NAMES = {
    "boolean": "boolean",
    "octet": "octet",
    "char": "char",
    "wchar": "wchar",
    "short": "short",
    "ushort": "unsigned_short",
    "long": "long",
    "ulong": "unsigned_long",
    "longlong": "long_long",
    "ulonglong": "unsigned_long_long",
    "float": "float",
    "double": "double",
    "longdouble": "long_double",
    "string": "string",
    "wstring": "wstring",
    "any": "any",
    "Object": "Object",
    "TypeCode": "TypeCode",
}

TK = {
    "boolean": "CORBA_tk_boolean",
    "octet": "CORBA_tk_octet",
    "char": "CORBA_tk_char",
    "wchar": "CORBA_tk_wchar",
    "short": "CORBA_tk_short",
    "ushort": "CORBA_tk_ushort",
    "long": "CORBA_tk_long",
    "ulong": "CORBA_tk_ulong",
    "longlong": "CORBA_tk_longlong",
    "ulonglong": "CORBA_tk_ulonglong",
    "float": "CORBA_tk_float",
    "double": "CORBA_tk_double",
    "longdouble": "CORBA_tk_longdouble",
    "string": "CORBA_tk_string",
    "wstring": "CORBA_tk_wstring",
}

INT_RANGES = cxx_backend.INT_RANGES

MODES = {"in": "RUSTORB_C_IN", "out": "RUSTORB_C_OUT", "inout": "RUSTORB_C_INOUT"}


class Writer(cxx_backend.Writer):
    def __call__(self, text=""):
        if text:
            self.lines.append("  " * self.level + text)
        else:
            self.lines.append("")


class Options(object):
    pass


def c_ident(name):
    return "_" + name if name in KEYWORDS else name


def file_base(path):
    return os.path.splitext(os.path.basename(path))[0]


def module_symbol(path):
    """The rustorb_c_module of the code of an IDL file."""
    return re.sub(r"[^A-Za-z0-9_]", "_", file_base(path)) + "_idl__module"


class CBackend(object):
    LANGUAGE = "C"

    def __init__(self, spec, options=None):
        self.spec = spec
        self.opt = options or Options()
        self.idl_name = os.path.basename(spec.path)
        self.base = file_base(spec.path)
        self.module = module_symbol(spec.path)
        # Descriptors of anonymous types: key -> name, and their text.
        self.anon = {}
        self.anon_lines = []
        # Named types of the file, for the module.
        self.named = []
        # Sequences and fixed types declared in the header.
        self.declared = set()

    # -- names -------------------------------------------------------------

    def full(self, node):
        if fe.is_interface(node) and fe.is_forward(node):
            full = fe.full_definition(node)
            return full if full is not None else node
        return cxx_backend.CxxBackend.full(self, node)

    def cname(self, node):
        """The scoped C name of a definition: ``Mod_Iface_Name``."""
        return "_".join(fe.scope_path(node))

    def scope_prefix(self, node):
        """``Mod_Iface_`` for a definition inside Mod::Iface (constants and
        enumerators), "" at the global scope."""
        path = fe.scope_path(node.parent) if node.parent is not None else ()
        return "".join(p + "_" for p in path)

    def enumerator(self, enum_node, name):
        return self.scope_prefix(enum_node) + name

    # -- checks ---------------------------------------------------------------

    def check_node(self, n, where):
        if fe.is_valuetype(n):
            raise fe.GeneratorError("valuetypes have no C mapping (rustorb#187)", where)
        if fe.is_native(n):
            raise fe.GeneratorError("native %s cannot be used in C" % n.name, where)
        if fe.is_interface(n):
            if getattr(n, "is_abstract", False):
                raise fe.GeneratorError(
                    "abstract interfaces have no C mapping (rustorb#187)", where
                )

    # -- types ------------------------------------------------------------------

    def ctype(self, t, where=None):
        """The C type of a Type (not of an anonymous array)."""
        k = t.kind
        if k in BASIC:
            return BASIC[k]
        if k == "void":
            return "void"
        if k == "string":
            return "CORBA_char*"
        if k == "wstring":
            return "CORBA_wchar*"
        if k == "any":
            return "CORBA_any"
        if k == "TypeCode":
            return "CORBA_TypeCode"
        if k == "Object":
            return "CORBA_Object"
        if k == "sequence":
            return self.seq_name(t, where)
        if k == "fixed":
            return "CORBA_fixed_%d_%d" % (t.digits, t.scale)
        if k == "array":
            raise fe.GeneratorError("an anonymous array must be named with a typedef in C", where)
        if k == "named":
            n = self.full(t.node)
            self.check_node(n, where)
            return self.cname(n)
        if k in ("int8", "bitmask", "bitset", "Principal"):
            raise fe.GeneratorError("%s has no C mapping (rustorb#187)" % k, where)
        raise fe.GeneratorError("no C type for %r" % t, where)

    def seq_elem_name(self, t, where):
        k = t.kind
        if k in SEQ_NAMES:
            return SEQ_NAMES[k]
        if k == "sequence":
            return self.seq_name(t, where)
        if k == "fixed":
            return "CORBA_fixed_%d_%d" % (t.digits, t.scale)
        return self.ctype(t, where)

    def seq_name(self, t, where):
        return "CORBA_sequence_" + self.seq_elem_name(t.content, where)

    def decl(self, t, name, where=None):
        """A declaration of ``name`` of type t (``CORBA_long a[3]``)."""
        dims = ""
        while t.kind == "array":
            dims += "[%d]" % t.length
            t = t.content
        return "%s %s%s" % (self.ctype(t, where), name, dims)

    def array_type(self, t, where):
        """``CORBA_long[3][4]``: the type name of an anonymous array."""
        dims = ""
        while t.kind == "array":
            dims += "[%d]" % t.length
            t = t.content
        return self.ctype(t, where) + dims

    def is_var(self, t):
        """Whether a type is variable-length (1.8)."""
        r = t.resolved()
        k = r.kind
        if k in ("string", "wstring", "sequence", "any", "Object", "TypeCode"):
            return True
        if k == "array":
            return self.is_var(r.content)
        if k == "named":
            n = self.full(r.node)
            if fe.is_interface(n):
                return True
            if fe.is_struct(n) or fe.is_exception(n):
                return any(self.is_var(fe.type_of(m.type, m)) for m in n.members)
            if fe.is_union(n):
                return any(self.is_var(fe.type_of(m.type, m)) for m in n.members)
        return False

    def category(self, t):
        """How a type is passed (tables 1-2 and 1-3): basic, objref,
        string, struct (fixed struct, union or fixed), varstruct, sequence,
        any, array, vararray."""
        r = t.resolved()
        k = r.kind
        if k in BASIC:
            return "basic"
        if k in ("Object", "TypeCode"):
            return "objref"
        if k in ("string", "wstring"):
            return "string"
        if k == "any":
            return "any"
        if k == "sequence":
            return "sequence"
        if k == "fixed":
            return "struct"
        if k == "array":
            return "vararray" if self.is_var(r) else "array"
        if k == "named":
            n = self.full(r.node)
            if fe.is_enum(n):
                return "basic"
            if fe.is_interface(n):
                return "objref"
            return "varstruct" if self.is_var(r) else "struct"
        raise fe.GeneratorError("no C mapping for %r" % r)

    def string_base(self, t):
        return "CORBA_wchar" if t.resolved().kind == "wstring" else "CORBA_char"

    def slice(self, t, where):
        """The slice type of a named array type."""
        if t.kind != "named":
            raise fe.GeneratorError("an anonymous array must be named with a typedef in C", where)
        return self.ctype(t, where) + "_slice"

    def param_type(self, t, direction, where):
        c = self.category(t)
        if c == "string":
            b = self.string_base(t)
            return "const %s*" % b if direction == "in" else "%s**" % b
        if c in ("array", "vararray"):
            s = self.slice(t, where)
            if direction == "in":
                return "const %s*" % s
            if direction == "out" and c == "vararray":
                return "%s**" % s
            return "%s*" % s
        ct = self.ctype(t, where)
        if c in ("basic", "objref"):
            return ct if direction == "in" else ct + "*"
        if direction == "in":
            return "const %s*" % ct
        if direction == "out" and c in ("varstruct", "sequence", "any"):
            return ct + "**"
        return ct + "*"

    def return_type(self, t, where):
        if t.kind == "void":
            return "void"
        c = self.category(t)
        if c == "string":
            return self.string_base(t) + "*"
        if c in ("array", "vararray"):
            return self.slice(t, where) + "*"
        ct = self.ctype(t, where)
        if c in ("varstruct", "sequence", "any"):
            return ct + "*"
        return ct

    def out_indirect(self, t):
        return self.category(t) in ("varstruct", "sequence", "any", "vararray")

    def result_indirect(self, t):
        return self.category(t) in ("varstruct", "sequence", "any", "array", "vararray")

    # -- descriptors --------------------------------------------------------------

    def desc(self, t, where=None):
        """An expression for the address of the descriptor of t."""
        k = t.kind
        if k in BASIC:
            return "&%s__desc" % BASIC[k]
        if k in ("string", "wstring"):
            if not t.bound:
                return "&CORBA_%s__desc" % k
            return self.anon_desc(
                ("str", k, t.bound),
                "%s, sizeof(%s), NULL, NULL, NULL, %dU, 0, NULL, NULL, -1, 0, 0"
                % (TK[k], self.ctype(t), t.bound),
            )
        if k == "any":
            return "&CORBA_any__desc"
        if k == "TypeCode":
            return "&CORBA_TypeCode__desc"
        if k == "Object":
            return "&CORBA_Object__desc"
        if k == "sequence":
            content = self.desc(t.content, where)
            return self.anon_desc(
                ("seq", content, t.bound),
                "CORBA_tk_sequence, sizeof(CORBA_sequence_octet), NULL, NULL, %s, %dU, 0, NULL, "
                "NULL, -1, 0, 0" % (content, t.bound),
            )
        if k == "array":
            content = self.desc(t.content, where)
            return self.anon_desc(
                ("array", content, t.length),
                "CORBA_tk_array, sizeof(%s), NULL, NULL, %s, %dU, 0, NULL, NULL, -1, 0, 0"
                % (self.array_type(t, where), content, t.length),
            )
        if k == "fixed":
            self.check_fixed(t, where)
            return self.anon_desc(
                ("fixed", t.digits, t.scale),
                "CORBA_tk_fixed, sizeof(CORBA_fixed_%d_%d), NULL, NULL, NULL, 0, 0, NULL, NULL, "
                "-1, %d, %d" % (t.digits, t.scale, t.digits, t.scale),
            )
        if k == "named":
            n = self.full(t.node)
            self.check_node(n, where)
            return "&%s__desc" % self.cname(n)
        self.ctype(t, where)
        raise fe.GeneratorError("no descriptor for %r" % t, where)

    def check_fixed(self, t, where):
        if t.digits < 1 or t.digits > 31 or t.scale < 0 or t.scale > t.digits:
            raise fe.GeneratorError("fixed<%d, %d> is not valid" % (t.digits, t.scale), where)

    def anon_desc(self, key, fields):
        name = self.anon.get(key)
        if name is None:
            name = "_rustorb_t%d" % len(self.anon)
            self.anon[key] = name
            self.anon_lines.append("static rustorb_c_cache %s_c;" % name)
            self.anon_lines.append(
                "static const rustorb_c_type %s = {%s, &%s_c};" % (name, fields, name)
            )
        return "&" + name

    # -- the header: declarations of types used ----------------------------------------

    def declare_type(self, h, t, where):
        """The sequence and fixed types t needs, declared once each."""
        k = t.kind
        if k == "sequence":
            self.declare_type(h, t.content, where)
            self.declare_sequence(h, t, where)
        elif k == "array":
            self.declare_type(h, t.content, where)
        elif k == "fixed":
            self.declare_fixed(h, t, where)

    def declare_fixed(self, h, t, where):
        self.check_fixed(t, where)
        name = "CORBA_fixed_%d_%d" % (t.digits, t.scale)
        if name in self.declared:
            return
        self.declared.add(name)
        h("#ifndef _%s_defined" % name)
        h("#define _%s_defined" % name)
        h("RUSTORB_C_FIXED(%d, %d);" % (t.digits, t.scale))
        h("#endif")

    def elem_alloc_desc(self, t, where):
        """The descriptor CORBA_sequence_<T>_allocbuf allocates with (only
        what freeing needs), or None for plain bytes."""
        k = t.kind
        if k in BASIC:
            return "&%s__desc" % BASIC[k]
        if k in ("string", "wstring"):
            return "&CORBA_%s__desc" % k
        if k == "sequence":
            return "&CORBA_sequence__desc"
        if k == "fixed":
            return None
        return self.desc(t, where)

    def declare_sequence(self, h, t, where):
        name = self.seq_name(t, where)
        if name in self.declared:
            return
        self.declared.add(name)
        elem = self.ctype(t.content, where)
        d = self.elem_alloc_desc(t.content, where)
        h("#ifndef _%s_defined" % name)
        h("#define _%s_defined" % name)
        h("RUSTORB_C_SEQUENCE(%s, %s);" % (name, elem))
        h("#define %s__alloc() ((%s*)rustorb_c_sequence_alloc())" % (name, name))
        if d is None:
            h(
                "#define %s_allocbuf(n) ((%s*)rustorb_c_alloc(NULL, (CORBA_unsigned_long)(n) * "
                "sizeof(%s)))" % (name, elem, elem)
            )
        else:
            h("#define %s_allocbuf(n) ((%s*)rustorb_c_alloc(%s, (n)))" % (name, elem, d))
        h("#endif")

    def named_common(self, h, node):
        """The descriptor, TC_ and __alloc of a named type."""
        name = self.cname(node)
        h("extern const rustorb_c_type %s__desc;" % name)
        h("#define TC_%s rustorb_c_type_tc(&%s__desc, &%s)" % (name, name, self.module))

    # -- literals ---------------------------------------------------------------------

    def literal(self, value, t, where=None):
        r = t.resolved()
        k = r.kind
        if k == "named" and fe.is_enum(r.node):
            return self.enumerator(r.node, value.name)
        if k == "boolean":
            return "CORBA_TRUE" if value else "CORBA_FALSE"
        if k == "char":
            c = value if isinstance(value, str) else chr(value)
            return "((CORBA_char)%d)" % ord(c)
        if k == "wchar":
            c = value if isinstance(value, str) else chr(value)
            return "((CORBA_wchar)%d)" % ord(c)
        if k == "string":
            data = str(value).encode("utf-8")
            return '"%s"' % "".join(_c_char(b) for b in data)
        if k == "wstring":
            units = []
            for ch in str(value):
                o = ord(ch)
                if o >= 0x10000:
                    o -= 0x10000
                    units += [0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)]
                else:
                    units.append(o)
            return "((const CORBA_wchar[]){%s})" % ", ".join(str(u) for u in units + [0])
        if k in ("float", "double", "longdouble"):
            v = float(value)
            if v != v:
                return "(0.0 / 0.0)"
            if v in (float("inf"), float("-inf")):
                return "(%s1.0 / 0.0)" % ("-" if v < 0 else "")
            text = repr(v) if k != "longdouble" else _decimal_text(value)
            if "." not in text and "e" not in text and "inf" not in text:
                text += ".0"
            suffix = {"float": "f", "double": "", "longdouble": "L"}[k]
            return "((%s)%s%s)" % (BASIC[k], text, suffix)
        if k == "fixed":
            return self.fixed_literal(value, r, where)
        if k in INT_RANGES:
            v = int(value)
            lo, hi = INT_RANGES[k]
            if v < lo or v > hi:
                raise fe.GeneratorError("constant %d out of range for %s" % (v, k), where)
            if k == "longlong":
                if v == lo:
                    return "(-9223372036854775807LL - 1)"
                return "((CORBA_long_long)%dLL)" % v
            if k == "ulonglong":
                return "((CORBA_unsigned_long_long)%dULL)" % v
            if k == "long":
                if v == lo:
                    return "((CORBA_long)(-2147483647 - 1))"
                return "((CORBA_long)%d)" % v
            if k == "ulong":
                return "((CORBA_unsigned_long)%dU)" % v
            return "((%s)%d)" % (BASIC[k], v)
        raise fe.GeneratorError("no C literal for a constant of type %r" % r, where)

    def fixed_literal(self, value, t, where):
        text = cxx_backend.fixed_text(value, t.digits, t.scale)
        negative = text.startswith("-")
        whole, _, frac = text.lstrip("-").partition(".")
        digits = whole.rjust(t.digits - t.scale, "0")[-(t.digits - t.scale):] if t.digits > t.scale else ""
        digits += frac.ljust(t.scale, "0")
        nibbles = [int(d) for d in digits]
        if len(nibbles) % 2 == 0:
            nibbles = [0] + nibbles
        nibbles.append(0xD if negative else 0xC)
        octets = [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]
        return "((CORBA_fixed_%d_%d){%d, %d, {%s}})" % (
            t.digits, t.scale, t.digits, t.scale, ", ".join("0x%02x" % o for o in octets))

    # -- generation ------------------------------------------------------------------

    def generate(self):
        """(header text, source text)."""
        h = Writer()
        c = Writer()
        guard = "RUSTORB_IDL_" + re.sub(r"[^A-Za-z0-9_]", "_", self.base).upper() + "_H"
        h(HEADER % self.idl_name)
        h("#ifndef %s" % guard)
        h("#define %s" % guard)
        h()
        h("#include <rustorb/runtime.h>")
        included = [f for f in self.spec.included_files() if f != fe.MESSAGING_IDL]
        for f in included:
            h('#include "%s.h"' % file_base(f))
        h()
        h("#ifdef __cplusplus")
        h('extern "C" {')
        h("#endif")
        h()
        h("extern const rustorb_c_module %s;" % self.module)
        for it in fe.definitions(self.spec):
            n = it.node
            if fe.is_module(n) or fe.is_operation(n) or fe.is_attribute(n):
                continue
            self.definition(h, c, n)
        h()
        h("#ifdef __cplusplus")
        h("}")
        h("#endif")
        h()
        h("#endif /* %s */" % guard)

        src = Writer()
        src(HEADER % self.idl_name)
        src("#include <stddef.h>")
        src()
        src('#include "%s.h"' % self.base)
        src()
        for line in self.anon_lines:
            src(line)
        src()
        for line in c.lines:
            src(line) if line else src()
        src()
        if self.named:
            src("static const rustorb_c_type* const _rustorb_types[] = {")
            for n in self.named:
                src("  &%s__desc," % n)
            src("};")
        src("static int _rustorb_registered;")
        src(
            "const rustorb_c_module %s = {%s, %dU, &_rustorb_registered};"
            % (self.module, "_rustorb_types" if self.named else "NULL", len(self.named), )
        )
        return h.text(), src.text()

    def definition(self, h, c, node):
        if fe.is_const(node):
            self.const(h, node)
        elif fe.is_enum(node):
            self.enum(h, c, node)
        elif fe.is_typedef(node):
            self.typedef(h, c, node)
        elif fe.is_exception(node):
            self.struct(h, c, node, exception=True)
        elif fe.is_struct(node):
            if fe.is_forward(node):
                self.forward_struct(h, node)
            else:
                self.struct(h, c, node)
        elif fe.is_union(node):
            if fe.is_forward(node):
                self.forward_struct(h, node)
            else:
                self.union(h, c, node)
        elif fe.is_interface(node):
            self.check_node(node, node)
            if fe.is_forward(node):
                self.interface_type(h, node)
            else:
                self.interface(h, c, node)
        elif fe.is_native(node):
            pass
        elif fe.is_valuetype(node):
            raise fe.GeneratorError("valuetypes have no C mapping (rustorb#187)", node)
        elif fe.is_bitmask(node) or fe.is_bitset(node):
            raise fe.GeneratorError(
                "the IDL 4 %s has no C mapping (rustorb#187)" % fe.kind_name(node), node
            )
        else:
            raise fe.GeneratorError(
                "%s definitions are not supported by the C backend" % fe.kind_name(node), node
            )

    def nested(self, h, c, scope):
        """The types and constants defined inside an interface, struct,
        union or exception, before it."""
        for d in fe.members_of(scope):
            if fe.is_operation(d) or fe.is_attribute(d):
                continue
            self.definition(h, c, d)

    # constants

    def const(self, h, node):
        t = fe.type_of(node.type, node)
        r = t.resolved()
        if r.kind == "fixed":
            self.declare_fixed(h, r, node)
        h()
        h("#define %s%s %s" % (self.scope_prefix(node), node.name, self.literal(node.value, t, node)))

    # enums

    def enum(self, h, c, node):
        name = self.cname(node)
        values = [v.name for v in node.values]
        h()
        h("typedef enum {")
        for i, v in enumerate(values):
            h("  %s%s" % (self.enumerator(node, v), "," if i + 1 < len(values) else ""))
        h("} %s;" % name)
        self.named_common(h, node)
        self.named.append(name)
        c()
        c("static const char* const _rustorb_e_%s[] = {%s};" % (
            name, ", ".join('"%s"' % v for v in values)))
        c("static rustorb_c_cache _rustorb_c_%s;" % name)
        c(
            'const rustorb_c_type %s__desc = {CORBA_tk_enum, sizeof(%s), "%s", "%s", NULL, 0, %dU, '
            "NULL, _rustorb_e_%s, -1, 0, 0, &_rustorb_c_%s};"
            % (name, name, fe.repository_id(node), node.name, len(values), name, name)
        )

    # typedefs

    def typedef(self, h, c, node):
        name = self.cname(node)
        t = fe.type_of(node.type, node)
        self.declare_type(h, t, node)
        h()
        if t.kind == "array":
            h("typedef %s;" % self.decl(t, name, node))
            h("typedef %s;" % self.decl(t.content, name + "_slice", node))
        else:
            h("typedef %s %s;" % (self.ctype(t, node), name))
            if t.kind == "named" and t.resolved().kind == "array":
                h("typedef %s_slice %s_slice;" % (self.ctype(t, node), name))
        self.named_common(h, node)
        cat = self.category(t)
        if cat in ("array", "vararray"):
            h("#define %s__alloc() ((%s_slice*)rustorb_c_alloc(&%s__desc, 1))" % (name, name, name))
        elif cat == "sequence":
            h("#define %s__alloc() ((%s*)rustorb_c_sequence_alloc())" % (name, name))
        elif cat in ("struct", "varstruct", "any"):
            h("#define %s__alloc() ((%s*)rustorb_c_alloc(&%s__desc, 1))" % (name, name, name))
        self.named.append(name)
        content = self.desc(t, node)
        c()
        c("static rustorb_c_cache _rustorb_c_%s;" % name)
        c(
            'const rustorb_c_type %s__desc = {CORBA_tk_alias, sizeof(%s), "%s", "%s", %s, 0, 0, '
            "NULL, NULL, -1, 0, 0, &_rustorb_c_%s};"
            % (name, name, fe.repository_id(node), node.name, content, name)
        )

    # structs and exceptions

    def forward_struct(self, h, node):
        name = self.cname(node)
        h()
        h("#ifndef _%s__fwd" % name)
        h("#define _%s__fwd" % name)
        h("typedef struct %s %s;" % (name, name))
        h("#endif")
        h("extern const rustorb_c_type %s__desc;" % name)

    def struct(self, h, c, node, exception=False):
        self.nested(h, c, node)
        name = self.cname(node)
        members = [(m.name, fe.type_of(m.type, m), m) for m in node.members]
        self.forward_struct(h, node)
        for _, t, m in members:
            self.declare_type(h, t, m)
        h("#define TC_%s rustorb_c_type_tc(&%s__desc, &%s)" % (name, name, self.module))
        if exception:
            h('#define ex_%s "%s"' % (name, fe.repository_id(node)))
        h("struct %s {" % name)
        for mname, t, m in members:
            h("  %s;" % self.decl(t, c_ident(mname), m))
        if not members:
            h("  CORBA_octet _rustorb_dummy;")
        h("};")
        h("#define %s__alloc() ((%s*)rustorb_c_alloc(&%s__desc, 1))" % (name, name, name))
        self.named.append(name)
        c()
        if members:
            c("static const rustorb_c_member _rustorb_m_%s[] = {" % name)
            for mname, t, m in members:
                c('  {"%s", %s, offsetof(%s, %s), 0},' % (mname, self.desc(t, m), name, c_ident(mname)))
            c("};")
        c("static rustorb_c_cache _rustorb_c_%s;" % name)
        c(
            'const rustorb_c_type %s__desc = {%s, sizeof(%s), "%s", "%s", NULL, 0, %dU, %s, NULL, '
            "-1, 0, 0, &_rustorb_c_%s};"
            % (
                name,
                "CORBA_tk_except" if exception else "CORBA_tk_struct",
                name,
                fe.repository_id(node),
                node.name,
                len(members),
                "_rustorb_m_" + name if members else "NULL",
                name,
            )
        )

    # unions

    def label_bits(self, label, disc):
        r = disc.resolved()
        if hasattr(label, "name") and hasattr(label, "parent"):
            v = [x.name for x in r.node.values].index(label.name)
        elif r.kind == "boolean":
            v = 1 if label else 0
        elif r.kind in ("char", "wchar"):
            v = ord(label) if isinstance(label, str) else int(label)
        else:
            v = int(label)
        return "%dULL" % (v & ((1 << 64) - 1))

    def union(self, h, c, node):
        self.nested(h, c, node)
        name = self.cname(node)
        disc, cases, default_index = cxx_backend.CxxBackend.union_cases(self, node)
        rdisc = disc.resolved()
        if not (
            rdisc.kind in INT_RANGES
            or rdisc.kind in ("boolean", "char", "wchar")
            or (rdisc.kind == "named" and fe.is_enum(rdisc.node))
        ) or rdisc.kind in ("octet", "int8"):
            raise fe.GeneratorError("unsupported union discriminator type %r" % rdisc, node)
        self.forward_struct(h, node)
        for _, _, t in cases:
            self.declare_type(h, t, node)
        h("#define TC_%s rustorb_c_type_tc(&%s__desc, &%s)" % (name, name, self.module))
        h("struct %s {" % name)
        h("  %s _d;" % self.ctype(disc, node))
        h("  union {")
        for _, m, t in cases:
            h("    %s;" % self.decl(t, c_ident(m), node))
        h("  } _u;")
        h("};")
        h("#define %s__alloc() ((%s*)rustorb_c_alloc(&%s__desc, 1))" % (name, name, name))
        self.named.append(name)
        entries = []
        default_entry = -1
        for i, (labels, m, t) in enumerate(cases):
            for label in labels:
                entries.append((m, t, self.label_bits(label, disc)))
            if i == default_index:
                default_entry = len(entries)
                entries.append((m, t, "0ULL"))
        c()
        c("static const rustorb_c_member _rustorb_m_%s[] = {" % name)
        for m, t, label in entries:
            c('  {"%s", %s, offsetof(%s, _u.%s), %s},' % (m, self.desc(t, node), name, c_ident(m), label))
        c("};")
        c("static rustorb_c_cache _rustorb_c_%s;" % name)
        c(
            'const rustorb_c_type %s__desc = {CORBA_tk_union, sizeof(%s), "%s", "%s", %s, 0, %dU, '
            "_rustorb_m_%s, NULL, %d, 0, 0, &_rustorb_c_%s};"
            % (name, name, fe.repository_id(node), node.name, self.desc(disc, node), len(entries),
               name, default_entry, name)
        )

    # interfaces

    def bases(self, node):
        return [self.full(b) for b in cxx_backend.CxxBackend.bases(self, node)]

    def ancestors(self, node):
        return [self.full(a) for a in cxx_backend.CxxBackend.ancestors(self, node)]

    def operations(self, node):
        return cxx_backend.CxxBackend.operations(self, node)

    def interface_type(self, h, node):
        name = self.cname(node)
        if getattr(node, "is_local", False):
            h()
            h("/* local interface %s: implemented by a POA_%s struct (POA_%s__init, no" % (
                node.name, name, name))
            h("   activation), whose local objects %s__create makes. */" % name)
        h()
        h("#ifndef _%s_defined" % name)
        h("#define _%s_defined" % name)
        h("typedef CORBA_Object %s;" % name)
        h("extern const rustorb_c_type %s__desc;" % name)
        h("#define TC_%s rustorb_c_type_tc(&%s__desc, &%s)" % (name, name, self.module))
        h("#endif")

    def epv_name(self, op):
        opname = op[0]
        if opname.startswith("_get_") or opname.startswith("_set_"):
            return opname
        return c_ident(op[1])

    def stub_name(self, iface, op):
        opname = op[0]
        if opname.startswith("_get_") or opname.startswith("_set_"):
            return "%s_%s" % (self.cname(iface), opname)
        return "%s_%s" % (self.cname(iface), op[1])

    def op_desc_name(self, owner, op):
        return "%s__op_%s" % (self.cname(owner), op[0])

    def params_decl(self, params, where):
        return "".join(
            ", %s %s" % (self.param_type(t, d, where), c_ident(p)) for p, t, d in params
        )

    def interface(self, h, c, node):
        # The type first: nested types may refer to it.
        self.interface_type(h, node)
        self.nested(h, c, node)
        name = self.cname(node)
        ops = self.operations(node)
        for op in ops:
            fe.reject_context(op[6], self.LANGUAGE) if fe.is_operation(op[6]) else None
            for _, t, _ in op[3]:
                self.declare_type(h, t, op[6])
            if op[2].kind != "void":
                self.declare_type(h, op[2], op[6])
        self.named.append(name)
        c()
        local = getattr(node, "is_local", False)
        c("static rustorb_c_cache _rustorb_c_%s;" % name)
        c(
            'const rustorb_c_type %s__desc = {%s, sizeof(CORBA_Object), "%s", "%s", '
            "NULL, 0, 0, NULL, NULL, -1, 0, 0, &_rustorb_c_%s};"
            % (name, "CORBA_tk_local_interface" if local else "CORBA_tk_objref",
               fe.repository_id(node), node.name, name)
        )
        # Operation descriptors.
        for op in ops:
            opname, method, ret, params, excs, oneway, d = op
            dn = self.op_desc_name(node, op)
            h("extern const rustorb_c_operation %s;" % dn)
            if params:
                c("static const rustorb_c_param _rustorb_p_%s[] = {" % dn)
                for p, t, direction in params:
                    ind = 1 if direction == "out" and self.out_indirect(t) else 0
                    c("  {%s, %s, %d}," % (self.desc(t, d), MODES[direction], ind))
                c("};")
            excs = [self.full(e) for e in excs]
            if excs:
                c("static const rustorb_c_type* const _rustorb_x_%s[] = {%s};" % (
                    dn, ", ".join("&%s__desc" % self.cname(e) for e in excs)))
            c(
                'const rustorb_c_operation %s = {"%s", %d, %s, %d, %dU, %s, %dU, %s, &%s};'
                % (
                    dn,
                    opname,
                    1 if oneway else 0,
                    "NULL" if ret.kind == "void" else self.desc(ret, d),
                    1 if ret.kind != "void" and self.result_indirect(ret) else 0,
                    len(params),
                    "_rustorb_p_" + dn if params else "NULL",
                    len(excs),
                    "_rustorb_x_" + dn if excs else "NULL",
                    self.module,
                )
            )
        # Stubs: the interface's operations and those of its bases.
        owners = [(node, op) for op in ops]
        seen = set(op[0] for op in ops)
        for a in self.ancestors(node):
            for op in self.operations(a):
                if op[0] not in seen:
                    seen.add(op[0])
                    owners.append((a, op))
        h()
        for owner, op in owners:
            self.stub(h, c, node, owner, op)
        # The skeleton.
        h()
        h("typedef struct POA_%s__epv {" % name)
        h("  void* _private;")
        for op in ops:
            opname, method, ret, params, excs, oneway, d = op
            h("  %s (*%s)(PortableServer_Servant _servant%s, CORBA_Environment* _ev);" % (
                self.return_type(ret, d), self.epv_name(op), self.params_decl(params, d)))
        h("} POA_%s__epv;" % name)
        h()
        h("typedef struct POA_%s__vepv {" % name)
        h("  PortableServer_ServantBase__epv* _base_epv;")
        for a in reversed(self.ancestors(node)):
            an = self.cname(a)
            h("  POA_%s__epv* %s_epv;" % (an, an))
        h("  POA_%s__epv* %s_epv;" % (name, name))
        h("} POA_%s__vepv;" % name)
        h()
        h("typedef struct POA_%s {" % name)
        h("  void* _private;")
        h("  POA_%s__vepv* vepv;" % name)
        h("} POA_%s;" % name)
        h()
        h("void POA_%s__init(PortableServer_Servant _servant, CORBA_Environment* _ev);" % name)
        h("void POA_%s__fini(PortableServer_Servant _servant, CORBA_Environment* _ev);" % name)
        if local:
            h("/* A local object calling impl (initialised with POA_%s__init; it must" % name)
            h("   outlive the object's references). */")
            h("%s %s__create(PortableServer_Servant impl, CORBA_Environment* _ev);" % (name, name))
        c()
        for owner, op in owners:
            self.skel(c, node, owner, op)
        ids = [fe.repository_id(node)] + [fe.repository_id(a) for a in self.ancestors(node)]
        c("static const char* const _rustorb_ids_%s[] = {%s};" % (
            name, ", ".join('"%s"' % i for i in ids)))
        if owners:
            c("static const rustorb_c_entry _rustorb_ent_%s[] = {" % name)
            for owner, op in owners:
                c("  {&%s, _rustorb_skel_%s_%s}," % (self.op_desc_name(owner, op), name, op[0]))
            c("};")
        c(
            "static const rustorb_c_class _rustorb_cls_%s = {_rustorb_ids_%s, %dU, %s, %dU, &%s};"
            % (name, name, len(ids), "_rustorb_ent_" + name if owners else "NULL", len(owners),
               self.module)
        )
        c("void POA_%s__init(PortableServer_Servant _servant, CORBA_Environment* _ev) {" % name)
        c("  rustorb_c_%s_init(_servant, &_rustorb_cls_%s, _ev);" % (
            "local" if local else "servant", name))
        c("}")
        if local:
            c("%s %s__create(PortableServer_Servant impl, CORBA_Environment* _ev) {" % (name, name))
            c("  return rustorb_c_local_object(impl, _ev);")
            c("}")
        c("void POA_%s__fini(PortableServer_Servant _servant, CORBA_Environment* _ev) {" % name)
        c("  rustorb_c_servant_fini(_servant, _ev);")
        c("}")

    def arg_expr(self, t, direction, pname):
        """The value pointer of a parameter for rustorb_c_invoke."""
        cat = self.category(t)
        if direction == "in" and cat in ("basic", "objref", "string"):
            return "(void*)&%s" % pname
        return "(void*)%s" % pname

    def stub(self, h, c, node, owner, op):
        opname, method, ret, params, excs, oneway, d = op
        sname = self.stub_name(node, op)
        rt = self.return_type(ret, d)
        sig = "%s %s(%s _obj%s, CORBA_Environment* _ev)" % (
            rt, sname, self.cname(node), self.params_decl(params, d))
        h("%s;" % sig)
        c()
        c("%s {" % sig)
        if params:
            c("  void* _a[%d];" % len(params))
            for i, (p, t, direction) in enumerate(params):
                c("  _a[%d] = %s;" % (i, self.arg_expr(t, direction, c_ident(p))))
        if ret.kind != "void":
            c("  %s _r;" % rt)
            c("  rustorb_c_invoke(_obj, &%s, %s, &_r, _ev);" % (
                self.op_desc_name(owner, op), "_a" if params else "NULL"))
            c("  return _r;")
        else:
            c("  rustorb_c_invoke(_obj, &%s, %s, NULL, _ev);" % (
                self.op_desc_name(owner, op), "_a" if params else "NULL"))
        c("}")

    def skel_arg(self, t, direction, i, where):
        cat = self.category(t)
        if direction == "in" and cat in ("basic", "objref"):
            return "*(%s*)_a[%d]" % (self.ctype(t, where), i)
        if direction == "in" and cat == "string":
            return "*(%s**)_a[%d]" % (self.string_base(t), i)
        return "(%s)_a[%d]" % (self.param_type(t, direction, where), i)

    def skel(self, c, node, owner, op):
        opname, method, ret, params, excs, oneway, d = op
        name = self.cname(node)
        on = self.cname(owner)
        c("static void _rustorb_skel_%s_%s(PortableServer_Servant _s, void** _a, void* _r, "
          "CORBA_Environment* _ev) {" % (name, opname))
        c("  POA_%s__epv* _e = ((POA_%s*)_s)->vepv->%s_epv;" % (on, name, on))
        if not params:
            c("  (void)_a;")
        if ret.kind == "void":
            c("  (void)_r;")
        c("  if (!_e || !_e->%s) {" % self.epv_name(op))
        c("    CORBA_exception_set_system(_ev, ex_CORBA_NO_IMPLEMENT, 0, CORBA_COMPLETED_NO);")
        c("    return;")
        c("  }")
        args = "".join(", " + self.skel_arg(t, direction, i, d) for i, (p, t, direction) in enumerate(params))
        call = "_e->%s(_s%s, _ev)" % (self.epv_name(op), args)
        if ret.kind == "void":
            c("  %s;" % call)
        else:
            c("  *(%s*)_r = %s;" % (self.return_type(ret, d), call))
        c("}")


def _c_char(b):
    if b == 0x22:
        return '\\"'
    if b == 0x5C:
        return "\\\\"
    if 0x20 <= b < 0x7F and b != 0x3F:
        return chr(b)
    return "\\%03o" % b


def _decimal_text(value):
    text = format(value, "f") if not isinstance(value, float) else repr(value)
    if "e" in text or "E" in text:
        from decimal import Decimal

        text = format(Decimal(text), "f")
    return text


def write_outputs(backend, outdir):
    """Writes ``<name>.h`` and ``<name>.c`` under ``outdir``; returns the
    paths written."""
    header, source = backend.generate()
    os.makedirs(outdir, exist_ok=True)
    written = []
    for suffix, text in ((".h", header), (".c", source)):
        path = os.path.join(outdir, backend.base + suffix)
        tmp = path + ".tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, path)
        written.append(path)
    return written
