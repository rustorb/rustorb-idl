def _decimal_text(value):
    text = format(value, "f") if not isinstance(value, float) else repr(value)
    if "e" in text or "E" in text:
        from decimal import Decimal

        text = format(Decimal(text), "f")
    return text


def write_outputs(backend, outdir):
    """Writes ``<name>C.rb`` and ``<name>S.rb`` under ``outdir``; returns
    the paths written."""
    stubs, skels = backend.generate()
    os.makedirs(outdir, exist_ok=True)
    written = []
    for suffix, text in (("C.rb", stubs), ("S.rb", skels)):
        path = os.path.join(outdir, backend.base + suffix)
        tmp = path + ".tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, path)
        written.append(path)
    return written
