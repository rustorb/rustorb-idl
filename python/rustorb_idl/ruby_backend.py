"""The Ruby backend: ``rustorb-idl -bruby``.

Writes ``<name>C.rb`` (the types and the stubs) and ``<name>S.rb`` (the
skeletons) for ``<name>.idl``, following the OMG Ruby Language Mapping
(RCLM 1.2) as rustorb's Ruby runtime (``ruby/`` of rustorb, MIT OR
Apache-2.0) implements it:

- an IDL module is a Ruby module, an interface ``Mod::I`` a Ruby module
  with a method per operation and attribute (``x`` and ``x=``),
  ``Mod::I._narrow`` and ``Mod::I._tc``; the skeleton is the class
  ``POA::Mod::I`` (a ``PortableServer::Servant``) in ``<name>S.rb``;
- structs, unions and exceptions are classes deriving from
  ``CORBA::Portable::Struct``, ``CORBA::Portable::Union`` and
  ``CORBA::UserException``; an enum is a module with an Integer constant
  per enumerator (also defined in the enclosing scope, as IDL scopes
  them); a constant is a Ruby constant; every type has ``_tc``;
- out and inout values come back from a call as an array after the
  result (a single value alone);
- names that must be Ruby constants start with an upper case letter
  (``module demo`` is ``Demo``); method, member and parameter names that
  are Ruby keywords or methods every object needs get an ``r_`` prefix.

TypeCodes are made when first used, so the order of the definitions and
recursive types need nothing from the generated code. IDL 4 (rustorb):
``int8`` is an Integer sent as an octet; a bitmask is a module of
``1 << position`` constants (values are Integers); a bitset is a
``Rustorb::Bitset`` class with an accessor per bitfield, sent as the
unsigned integer that holds its bits; ``@default`` gives the value of a
struct member that ``new`` does not get and ``@range`` / ``@min`` /
``@max`` are checked when a struct is sent or received. Valuetypes and
abstract interfaces are errors (rustorb#188). A local interface is a
module that implementations include, with ``CORBA::LocalObject`` as their
base.
"""

import math
import os

from . import cxx_backend
from . import frontend as fe

#: Must match Rustorb::GENERATED_CODE_VERSION.
GENERATED_CODE_VERSION = 1

HEADER = (
    "# frozen_string_literal: true\n"
    "#\n"
    "# Generated by rustorb-idl from %s. Do not edit.\n"
    "#\n"
    "# This file is not covered by the license of rustorb-idl.\n"
)

KEYWORDS = {
    "alias", "and", "begin", "BEGIN", "break", "case", "class", "def", "defined?", "do",
    "else", "elsif", "end", "END", "ensure", "false", "for", "if", "in", "module", "next",
    "nil", "not", "or", "redo", "rescue", "retry", "return", "self", "super", "then", "true",
    "undef", "unless", "until", "when", "while", "yield", "__FILE__", "__LINE__",
    "__ENCODING__",
}

# Methods of every object, and those the runtime calls on stubs, servants
# and values, that an IDL name must not replace.
RESERVED_METHODS = {
    "Array", "class", "clone", "define_singleton_method", "dup", "eql", "equal", "extend",
    "freeze", "frozen", "hash", "initialize", "inspect", "instance_of", "instance_variable_get",
    "instance_variable_set", "instance_variables", "is_a", "kind_of", "lambda", "method",
    "methods", "nil", "object_id", "public_send", "raise", "respond_to", "send",
    "singleton_class", "to_s", "warn",
}

TC_BASIC = {
    "short": "_tc_short",
    "long": "_tc_long",
    "ushort": "_tc_ushort",
    "ulong": "_tc_ulong",
    "longlong": "_tc_longlong",
    "ulonglong": "_tc_ulonglong",
    "float": "_tc_float",
    "double": "_tc_double",
    "longdouble": "_tc_longdouble",
    "boolean": "_tc_boolean",
    "char": "_tc_char",
    "wchar": "_tc_wchar",
    "octet": "_tc_octet",
    "any": "_tc_any",
    "Object": "_tc_Object",
    "TypeCode": "_tc_TypeCode",
}

INT_KINDS = ("short", "long", "ushort", "ulong", "longlong", "ulonglong", "octet", "int8")


def holder_tk(bits):
    """The TCKind of the unsigned integer that holds ``bits`` bits, as a
    bitmask or a bitset is sent."""
    if bits <= 8:
        return "TK_OCTET"
    if bits <= 16:
        return "TK_USHORT"
    if bits <= 32:
        return "TK_ULONG"
    return "TK_ULONGLONG"


HOLDER_TC = {"TK_OCTET": "_tc_octet", "TK_USHORT": "_tc_ushort", "TK_ULONG": "_tc_ulong",
             "TK_ULONGLONG": "_tc_ulonglong"}


class Writer(cxx_backend.Writer):
    def __call__(self, text=""):
        if text:
            self.lines.append("  " * self.level + text)
        else:
            self.lines.append("")


class Options(object):
    pass


def const_name(name):
    """A Ruby constant name for an IDL identifier."""
    n = name[0].upper() + name[1:]
    return "R_" + n if n in ("BEGIN", "END") else n


def method_name(name):
    """A Ruby method (or member) name for an IDL identifier."""
    return "r_" + name if name in KEYWORDS or name in RESERVED_METHODS else name


def local_name(name):
    """A Ruby parameter name for an IDL identifier."""
    if name in KEYWORDS or not (name[0].islower() or name[0] == "_"):
        return "_" + name
    return name


def file_base(path):
    return os.path.splitext(os.path.basename(path))[0]


def ruby_string(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "#":
            out.append("\\#")
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append("\\u{%x}" % o)
    out.append('"')
    return "".join(out)


class RubyBackend(object):
    LANGUAGE = "Ruby"

    def __init__(self, spec, options=None):
        self.spec = spec
        self.opt = options or Options()
        self.idl_name = os.path.basename(spec.path)
        self.base = file_base(spec.path)

    # -- names -------------------------------------------------------------

    def full(self, node):
        if fe.is_forward(node):
            full = fe.full_definition(node)
            return full if full is not None else node
        return node

    def path(self, node):
        """``::Mod::Iface::Name``: the Ruby constant of a definition."""
        return "".join("::" + const_name(p) for p in fe.scope_path(node))

    def poa_path(self, node):
        return "::POA" + self.path(node)

    # -- checks -------------------------------------------------------------

    def check_node(self, n, where):
        if fe.is_valuetype(n):
            raise fe.GeneratorError("valuetypes are not supported by the Ruby backend yet (rustorb#188)", where)
        if fe.is_native(n):
            raise fe.GeneratorError("native %s cannot be used in Ruby" % n.name, where)
        if fe.is_interface(n):
            if getattr(n, "is_abstract", False):
                raise fe.GeneratorError(
                    "abstract interfaces are not supported by the Ruby backend yet (rustorb#188)", where
                )

    # -- TypeCodes ------------------------------------------------------------

    def tc(self, t, where=None):
        """An expression for the TypeCode of a :class:`frontend.Type`."""
        k = t.kind
        if k in TC_BASIC:
            return "::CORBA." + TC_BASIC[k]
        if k in ("string", "wstring"):
            if t.bound:
                return "::CORBA::TypeCode.create_%s_tc(%d)" % (k, t.bound)
            return "::CORBA._tc_" + k
        if k == "sequence":
            return "::CORBA::TypeCode.create_sequence_tc(%d, %s)" % (t.bound, self.tc(t.content, where))
        if k == "array":
            return "::CORBA::TypeCode.create_array_tc(%d, %s)" % (t.length, self.tc(t.content, where))
        if k == "fixed":
            if t.digits < 1 or t.digits > 31 or t.scale < 0 or t.scale > t.digits:
                raise fe.GeneratorError("fixed<%d, %d> is not valid" % (t.digits, t.scale), where)
            return "::CORBA::TypeCode.create_fixed_tc(%d, %d)" % (t.digits, t.scale)
        if k == "named":
            n = self.full(t.node)
            self.check_node(n, where)
            return self.path(n) + "._tc"
        if k == "int8":
            return "::CORBA._tc_int8"
        if k in ("bitmask", "bitset"):
            return self.path(t.node) + "._tc"
        if k == "Principal":
            raise fe.GeneratorError("%s is not supported by the Ruby backend (rustorb#188)" % k, where)
        raise fe.GeneratorError("no TypeCode for %r" % t, where)

    # -- values -----------------------------------------------------------------

    def literal(self, value, t, where=None):
        r = t.resolved()
        k = r.kind
        if k == "named" and fe.is_enum(r.node):
            return self.enumerator_ref(value)
        if k == "boolean":
            return "true" if value else "false"
        if k in ("float", "double", "longdouble"):
            v = float(value)
            if v != v:
                text = "::Float::NAN"
            elif math.isinf(v):
                text = "::Float::INFINITY" if v > 0 else "-::Float::INFINITY"
            else:
                text = repr(v)
            return "::CORBA::LongDouble.new(%s)" % text if k == "longdouble" else text
        if k == "fixed":
            return 'BigDecimal("%s")' % _decimal_text(value)
        if k in ("string", "char"):
            return ruby_string(value if isinstance(value, str) else chr(value))
        if k == "wchar":
            return str(ord(value) if isinstance(value, str) else int(value))
        if k == "wstring":
            units = []
            for ch in value:
                o = ord(ch)
                if o > 0xFFFF:
                    o -= 0x10000
                    units += [0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)]
                else:
                    units.append(o)
            return "[%s].freeze" % ", ".join(str(u) for u in units)
        if k == "octet" or k in INT_KINDS:
            return str(int(value))
        return repr(value)

    def enumerator_ref(self, item):
        enum = item.parent
        return "%s::%s" % (self.path(enum), const_name(item.name))

    # -- the C file ---------------------------------------------------------------

    def generate(self):
        """(stub text, skeleton text)."""
        body = Writer()
        self.w = body
        self.skels = []
        self.open_modules = ()
        for it in fe.definitions(self.spec):
            n = it.node
            if fe.is_module(n) or fe.is_operation(n) or fe.is_attribute(n):
                continue
            self.enter(it.modules)
            self.definition(n)
        self.enter(())

        w = Writer()
        w(HEADER % self.idl_name)
        w('require "rustorb"')
        for f in self.spec.included_files():
            if f == fe.MESSAGING_IDL:
                continue
            w(self.require_line(f, "C"))
        w()
        w("::Rustorb.check_generated_code(%d)" % GENERATED_CODE_VERSION)
        w()
        w.lines.extend(body.lines)

        s = Writer()
        s(HEADER % self.idl_name)
        s('require_relative "%sC"' % self.base)
        s()
        self.w = s
        for node in self.skels:
            self.skeleton(s, node)
        return w.text(), s.text()

    def require_line(self, path, suffix):
        if os.path.dirname(os.path.abspath(path)) == os.path.abspath(cli_idl_dir()):
            return 'require "%s%s"' % (file_base(path), suffix)
        return 'require_relative "%s%s"' % (file_base(path), suffix)

    def enter(self, modules):
        """Closes and opens Ruby modules so that the writer is inside
        ``modules``."""
        w = self.w
        keep = 0
        while (
            keep < len(self.open_modules)
            and keep < len(modules)
            and self.open_modules[keep] == modules[keep]
        ):
            keep += 1
        for _ in range(len(self.open_modules) - keep):
            w.dedent()
            w("end")
        if len(self.open_modules) > keep and len(modules) == keep:
            w()
        for m in modules[keep:]:
            w("module %s" % const_name(m))
            w.indent()
        self.open_modules = tuple(modules)

    def definition(self, node):
        if fe.is_const(node):
            self.const(node)
        elif fe.is_enum(node):
            self.enum(node)
        elif fe.is_typedef(node):
            self.typedef(node)
        elif fe.is_exception(node):
            self.struct(node, exception=True)
        elif fe.is_struct(node) or fe.is_union(node):
            if fe.is_forward(node):
                self.w("# forward declaration of %s" % node.name)
                self.w()
            elif fe.is_struct(node):
                self.struct(node)
            else:
                self.union(node)
        elif fe.is_interface(node):
            self.check_node(node, node)
            if fe.is_forward(node):
                self.w("# forward declaration of interface %s" % node.name)
                self.w()
            else:
                self.interface(node)
        elif fe.is_native(node):
            self.w("# native %s" % node.name)
            self.w()
        elif fe.is_valuetype(node):
            raise fe.GeneratorError("valuetypes are not supported by the Ruby backend yet (rustorb#188)", node)
        elif fe.is_bitmask(node):
            self.bitmask(node)
        elif fe.is_bitset(node):
            self.bitset(node)
        else:
            raise fe.GeneratorError(
                "%s definitions are not supported by the Ruby backend" % fe.kind_name(node), node
            )

    def nested(self, scope):
        for d in fe.members_of(scope):
            if fe.is_operation(d) or fe.is_attribute(d):
                continue
            self.definition(d)

    def tc_method(self, node, expr, recursive=True):
        w = self.w
        w("def self._tc")
        w.indent()
        w(
            "::Rustorb.lazy_tc(self, ID%s) { %s }"
            % ("" if recursive else ", recursive: false", expr)
        )
        w.dedent()
        w("end")

    # constants and enums

    def const(self, node):
        t = fe.type_of(node.type, node)
        self.w("%s = %s" % (const_name(node.name), self.literal(node.value, t, node)))
        self.w()

    def enum(self, node):
        w = self.w
        names = [v.name for v in node.values]
        w("module %s" % const_name(node.name))
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        for i, n in enumerate(names):
            w("%s = %d" % (const_name(n), i))
        w("ENUMERATORS = [%s].freeze" % ", ".join('"%s"' % n for n in names))
        w()
        self.tc_method(
            node,
            '::CORBA::TypeCode.create_enum_tc(ID, "%s", ENUMERATORS)' % node.name,
        )
        w.dedent()
        w("end")
        for i, n in enumerate(names):
            w("%s = %d" % (const_name(n), i))
        w()

    # IDL 4 bitmasks and bitsets

    def bitmask(self, node):
        w = self.w
        w("module %s" % const_name(node.name))
        w.indent()
        w("BIT_BOUND = %d" % node.bit_bound)
        for v in node.values:
            w("%s = 1 << %d" % (const_name(v.name), v.position))
        w()
        w("def self._tc = ::CORBA.%s" % HOLDER_TC[holder_tk(node.bit_bound)])
        w.dedent()
        w("end")
        w()

    def bitset(self, node):
        w = self.w
        if node.base is not None:
            raise fe.GeneratorError("bitset inheritance is not supported", node)
        fields = []
        for f in node.bitfields:
            if not f.name:
                continue
            kind = cxx_backend.CxxBackend.bitfield_type(self, f, node)
            if kind == "boolean":
                how = "boolean"
            elif cxx_backend.INT_RANGES[kind][0] < 0:
                how = "signed"
            else:
                how = "unsigned"
            fields.append((method_name(f.name), f.position, f.bits, how))
        name = const_name(node.name)
        w("class %s < ::Rustorb::Bitset" % name)
        w.indent()
        w("FIELDS = [%s].freeze" % ", ".join('["%s", %d, %d, :%s].freeze' % f for f in fields))
        if fields:
            w("attr_accessor %s" % ", ".join(":" + f[0] for f in fields))
        w()
        w("def self._tc")
        w.indent()
        w("@_tc ||= ::CORBA::TypeCode._bitset_tc(::CORBA::%s, self)" % holder_tk(max(node.bit_size, 1)))
        w.dedent()
        w("end")
        w.dedent()
        w("end")
        w()

    # typedefs

    def typedef(self, node):
        w = self.w
        t = fe.type_of(node.type, node)
        tc = '::CORBA::TypeCode.create_alias_tc(ID, "%s", %s)' % (node.name, self.tc(t, node))
        target = None
        if t.kind == "named":
            target = self.full(t.node)
        if target is not None and (fe.is_struct(target) or fe.is_union(target)):
            w("class %s < %s" % (const_name(node.name), self.path(target)))
        else:
            w("module %s" % const_name(node.name))
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        w()
        self.tc_method(node, tc, recursive=False)
        if target is not None and fe.is_interface(target):
            w()
            w("def self._narrow(obj) = %s._narrow(obj)" % self.path(target))
        w.dedent()
        w("end")
        w()

    # structs and exceptions

    def struct(self, node, exception=False):
        w = self.w
        if getattr(node, "base", None) is not None:
            raise fe.GeneratorError("struct inheritance is not supported", node)
        members = [(m.name, fe.type_of(m.type, m), m) for m in node.members]
        base = "::CORBA::UserException" if exception else "::CORBA::Portable::Struct"
        name = const_name(node.name)
        w("class %s < %s" % (name, base))
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        w("MEMBERS = [%s].freeze" % ", ".join('"%s"' % method_name(m) for m, _, _ in members))
        if members:
            w("attr_accessor %s" % ", ".join(":" + method_name(m) for m, _, _ in members))
        if not exception:
            defaults = [(method_name(m), self.member_default(d, t)) for m, t, d in members]
            defaults = [(m, v) for m, v in defaults if v is not None]
            if defaults:
                w("DEFAULTS = { %s }.freeze" % ", ".join('"%s" => %s' % mv for mv in defaults))
            ranges = [(method_name(m), cxx_backend.CxxBackend.member_range(self, d, t)) for m, t, d in members]
            ranges = [(m, r) for m, r in ranges if r is not None]
            if ranges:
                w(
                    "RANGES = { %s }.freeze"
                    % ", ".join(
                        '"%s" => [%s, %s].freeze' % (m, lo or "nil", hi or "nil") for m, (lo, hi) in ranges
                    )
                )
        w()
        self.tc_method(
            node,
            '::CORBA::TypeCode.create_%s_tc(ID, "%s", [%s])'
            % (
                "exception" if exception else "struct",
                node.name,
                ", ".join('["%s", %s]' % (m, self.tc(t, d)) for m, t, d in members),
            ),
        )
        self.nested_inside(node)
        w.dedent()
        w("end")
        w("::Rustorb.register_type(%s)" % name)
        w()

    def member_default(self, m, t):
        """The Ruby value of a member's ``@default``, or None."""
        a = fe.annotation(m, "default")
        if a is None:
            return None
        r = t.resolved()
        if r.kind not in INT_KINDS and r.kind not in ("boolean", "float", "double", "string"):
            raise fe.GeneratorError("@default of a %s member is not supported" % r.kind, m)
        value = a.value
        if r.kind == "boolean":
            value = str(value).upper() == "TRUE"
        elif r.kind == "string":
            value = str(value).strip('"')
        return self.literal(value, r)

    def nested_inside(self, node):
        inner = [
            d for d in fe.members_of(node) if not (fe.is_operation(d) or fe.is_attribute(d))
        ]
        if inner:
            self.w()
            self.nested(node)
            if self.w.lines and self.w.lines[-1] == "":
                self.w.lines.pop()

    # unions

    def union(self, node):
        w = self.w
        disc = fe.type_of(node.discriminator_type, node)
        rdisc = disc.resolved()
        if rdisc.kind not in INT_KINDS + ("boolean", "char", "wchar") and not (
            rdisc.kind == "named" and fe.is_enum(rdisc.node)
        ):
            raise fe.GeneratorError("unsupported union discriminator type %r" % disc, node)
        cases = []
        members = []
        for m in node.members:
            t = fe.type_of(m.type, m)
            members.append((m.name, t))
            for label in m.labels:
                cases.append((self.literal(label, disc, m), m.name, t, m))
            if m.is_default:
                cases.append((":default", m.name, t, m))
        name = const_name(node.name)
        w("class %s < ::CORBA::Portable::Union" % name)
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        w()
        self.tc_method(
            node,
            '::CORBA::TypeCode.create_union_tc(ID, "%s", %s, [%s])'
            % (
                node.name,
                self.tc(disc, node),
                ", ".join('[%s, "%s", %s]' % (lbl, n, self.tc(t, d)) for lbl, n, t, d in cases),
            ),
        )
        for m, _ in members:
            w()
            w('def %s = _get("%s")' % (method_name(m), m))
            w()
            w("def %s=(value)" % method_name(m))
            w.indent()
            w('_put("%s", value)' % m)
            w.dedent()
            w("end")
        self.nested_inside(node)
        w.dedent()
        w("end")
        w("::Rustorb.register_type(%s)" % name)
        w()

    # interfaces

    def bases(self, node):
        return [self.full(b) for b in cxx_backend.CxxBackend.bases(self, node)]

    def ancestors(self, node):
        return [self.full(a) for a in cxx_backend.CxxBackend.ancestors(self, node)]

    def operations(self, node):
        return cxx_backend.CxxBackend.operations(self, node)

    def op_method(self, op):
        opname, attr = op[0], op[1]
        if opname.startswith("_set_"):
            return method_name(attr) + "="
        return method_name(attr)

    def op_expr(self, op):
        opname, _, ret, params, excs, oneway, d = op
        args = ['"%s"' % opname]
        if ret.kind != "void":
            args.append("result: %s" % self.tc(ret, d))
        if params:
            args.append(
                "params: [%s]" % ", ".join("[:%s, %s]" % (dr, self.tc(t, d)) for _, t, dr in params)
            )
        if excs:
            args.append("exceptions: [%s]" % ", ".join(self.path(self.full(e)) for e in excs))
        if oneway:
            args.append("oneway: true")
        return "::Rustorb::Operation.new(%s)" % ", ".join(args)

    def local_interface(self, node):
        """A module the implementations include (with CORBA::LocalObject as
        their base): no stub, no skeleton."""
        w = self.w
        w("module %s" % const_name(node.name))
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        w("extend ::Rustorb::LocalInterfaceModule")
        for b in self.bases(node):
            self.check_node(b, node)
            w("include %s" % self.path(b))
        w()
        w("def self._tc")
        w.indent()
        w('@_tc ||= ::CORBA::TypeCode.create_local_interface_tc(ID, "%s")' % node.name)
        w.dedent()
        w("end")
        inner = [d for d in fe.members_of(node) if not (fe.is_operation(d) or fe.is_attribute(d))]
        if inner:
            w()
            self.nested(node)
            if w.lines[-1] == "":
                w.lines.pop()
        w.dedent()
        w("end")
        w()

    def interface(self, node):
        w = self.w
        if getattr(node, "is_local", False):
            return self.local_interface(node)
        name = const_name(node.name)
        path = self.path(node)
        ops = self.operations(node)
        for op in ops:
            if fe.is_operation(op[6]):
                fe.reject_context(op[6], self.LANGUAGE)
        w("module %s" % name)
        w.indent()
        w('ID = "%s"' % fe.repository_id(node))
        w("extend ::Rustorb::InterfaceModule")
        for b in self.bases(node):
            self.check_node(b, node)
            w("include %s" % self.path(b))
        w()
        w("def self._tc")
        w.indent()
        w('@_tc ||= ::CORBA::TypeCode.create_interface_tc(ID, "%s")' % node.name)
        w.dedent()
        w("end")
        inner = [d for d in fe.members_of(node) if not (fe.is_operation(d) or fe.is_attribute(d))]
        if inner:
            w()
            self.nested(node)
            if w.lines[-1] == "":
                w.lines.pop()
        w()
        w("def self._ops")
        w.indent()
        if ops:
            w("@_ops ||= {")
            w.indent()
            for i, op in enumerate(ops):
                w('"%s" => %s%s' % (op[0], self.op_expr(op), "," if i + 1 < len(ops) else ""))
            w.dedent()
            w("}.freeze")
        else:
            w("{}.freeze")
        w.dedent()
        w("end")
        for op in ops:
            opname, _, _, params, _, _, _ = op
            args = [local_name(p) for p, _, dr in params if dr != "out"]
            w()
            meth = self.op_method(op)
            call = '_invoke(%s._ops["%s"], [%s])' % (path, opname, ", ".join(args))
            if meth.endswith("="):
                w("def %s(%s)" % (meth, ", ".join(args)))
                w.indent()
                w(call)
                w.dedent()
                w("end")
            else:
                w("def %s%s = %s" % (meth, "(%s)" % ", ".join(args) if args else "", call))
        w()
        w("::Rustorb.stub_class(self)")
        w.dedent()
        w("end")
        w()
        self.skels.append(node)

    # -- the S file -------------------------------------------------------------------

    def skeleton(self, s, node):
        path = fe.scope_path(node)
        for p in ["POA"] + [const_name(m) for m in path[:-1]]:
            s("module %s" % p)
            s.indent()
        ids = [fe.repository_id(node)] + [fe.repository_id(a) for a in self.ancestors(node)]
        s("class %s < ::PortableServer::Servant" % const_name(node.name))
        s.indent()
        s("IDS = [%s].freeze" % ", ".join('"%s"' % i for i in ids))
        s()
        s("def self._operations")
        s.indent()
        entries = []
        seen = set()
        for owner in [node] + self.ancestors(node):
            for op in self.operations(owner):
                if op[0] in seen:
                    continue
                seen.add(op[0])
                entries.append(
                    '"%s" => [:%s, %s._ops["%s"]]'
                    % (op[0], self.op_method(op), self.path(owner), op[0])
                )
        if entries:
            s("@_operations ||= {")
            s.indent()
            for i, e in enumerate(entries):
                s(e + ("," if i + 1 < len(entries) else ""))
            s.dedent()
            s("}.freeze")
        else:
            s("{}.freeze")
        s.dedent()
        s("end")
        s.dedent()
        s("end")
        for _ in range(len(path)):
            s.dedent()
            s("end")
        s()


