"""The C# backend: ``rustorb-idl -bcsharp``.

Writes ``<name>.cs`` for ``<name>.idl``, following the IDL4 to C# Language
Mapping 1.0 (formal/21-07-01) with its CORBA profile (annex A.1):

- modules are namespaces; constants are members of a ``Constants`` class
  in each namespace (7.2.3.2); typedefs are replaced by the type they name
  (7.2.4.6);
- structs and unions are classes implementing ``IEquatable<T>`` with a
  property per member (7.2.4.3); a union has the read-only
  ``Discriminator`` and ``Set<Member>(value, discriminator)``; enums are
  enums; sequences are ``Omg.Types.ISequence<T>``, arrays C# arrays;
- exceptions derive from ``Corba.UserException`` (A.1.1);
- an interface ``I`` is ``IIOperations``, ``II : Corba.IObject,
  IIOperations`` and the class ``I : Corba.Object, II`` (A.1.5), which is
  the stub and holds the types and constants defined in the interface.

What the mapping leaves to the platform follows the rustorb runtime
(``dotnet/`` of rustorb, MIT OR Apache-2.0): each type has a static class
``<Name>Helper`` (``insert``, ``extract``, ``type``, ``id``, ``read``,
``write``, and ``narrow`` / ``unchecked_narrow`` for interfaces, as in the
IDL to Java mapping) and each interface a servant base ``<Name>POA``. The
code calls only the runtime's public API (``Corba``, ``PortableServer``,
``Omg.Types`` and the ``Rustorb`` classes the generated code uses).

The names are those of the IDL (the IDL naming scheme, 7.1.1.1);
``-Wbdotnet_naming`` applies the .NET naming scheme (7.1.1.2, Table 8.1)
instead. Names that are C# keywords get ``@``, and names that clash with
the ones the mapping or the runtime introduces get ``_``.

A valuetype ``V`` is the abstract class ``V`` of IDL4 to C# 7.6 (state
members as properties, private ones protected; operations, those of the
interfaces it supports and factories as abstract methods, factories marked
``[Omg.Types.Factory]``), deriving from its concrete base or
``Corba.ValueBase``; an abstract valuetype is the interface ``IV``. The
rest is rustorb's, after the C++ mapping: a valuetype without operations
also has the class ``OBV_<Module>.V`` with a constructor of every state
member, which its default factory makes; a value box is a class with the
boxed value as the property ``value``; a custom valuetype implements
``Corba.ICustomMarshal``. The default factories and the TypeCodes of the
valuetypes are registered by a module initialiser. An abstract interface
``A`` is the interface ``IA`` and the stub class ``A``; each concrete
interface also has the tie ``<Name>POATie``.

Local interfaces and ``-Wbami`` are not mapped yet (rustorb#186).
"""

