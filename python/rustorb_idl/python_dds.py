"""DDS types in the Python backend: ``-bpython -Wbdds`` / ``-Wbdds_only``.

For ``Foo.idl`` it writes ``Foo_dds.py``, which declares the structs,
unions, enums, bitmasks and typedefs of the file for the ``rustorb_dds``
package (rustorb-dds's Python binding) with its decorators
(``@rustorb_dds.struct``...), and its constants. The types are described
to DDS as DDS-XTypes TypeObjects, the same as the C, C++ and Rust code
of other generators for the same IDL, so that they match.

Each IDL module is a module object in ``Foo_dds``, nested ones in the
outer ones::

    from Foo_dds import HelloWorld
    HelloWorld.Greeting(index=1, message="hi")

The types of included files are those of their own ``*_dds.py`` modules,
which ``Foo_dds.py`` imports. ``-Wbdds`` writes ``Foo_dds.py`` as well
as the CORBA code; ``-Wbdds_only`` writes only it, and then allows the
annotations GIOP has no form for and the types only DDS has (``@optional``,
``@external``, ``int8``, ``bitmask``...).

The annotations read are the ones of the Rust backend (see rust_dds.py):
``@key``, ``@id``, ``@autoid``, ``@hashid``, ``@optional``, ``@external``,
``@must_understand``, ``@final``, ``@appendable``, ``@mutable``,
``@extensibility``, ``@nested``, ``@default_nested``, ``@topic``,
``@bit_bound``, ``@value``, ``@position`` and ``@default_literal``.
"""

import keyword
import os
import re

from . import frontend as fe

HEADER = (
    "# Generated by rustorb-idl from %s. Do not edit.\n"
    "#\n"
    "# This file is not covered by the license of rustorb-idl.\n"
)

# IDL type -> rustorb_dds type
PRIMITIVE = {
    "boolean": "boolean",
    "octet": "byte",
    "int8": "int8",
    "uint8": "uint8",
    "short": "int16",
    "ushort": "uint16",
    "long": "int32",
    "ulong": "uint32",
    "longlong": "int64",
    "ulonglong": "uint64",
    "float": "float32",
    "double": "float64",
    "longdouble": "float128",
    "char": "char8",
    "wchar": "char16",
}

# Member annotations that change what is written or read, which rustorb_dds
# does not implement: refused rather than ignored.
NOT_YET = ("non_serialized", "default", "try_construct")

# The prefix of the names the generated code uses for itself, which no IDL
# identifier can have.
P = "_0_"


def dds_module_of_file(path):
    """The Python module of the DDS types of an IDL file:
    ``Foo.idl`` -> ``Foo_dds``."""
    base = os.path.basename(path)
    if base.lower().endswith(".idl"):
        base = base[:-4]
    base = re.sub(r"[^0-9A-Za-z_]", "_", base)
    if base[:1].isdigit():
        base = "_" + base
    return base + "_dds"


def py_name(name):
    """An IDL identifier as a Python one: keywords get a leading ``_``."""
    if keyword.iskeyword(name) or name in ("None", "True", "False"):
        return "_" + name
    return name


class Writer(object):
    def __init__(self):
        self.lines = []
        self.level = 0

    def __call__(self, text=""):
        self.lines.append("    " * self.level + text if text else "")

    def indent(self):
        self.level += 1

    def dedent(self):
        self.level -= 1

    def text(self):
        return "\n".join(self.lines) + "\n"


class PythonDds(object):
    """Writes ``Foo_dds.py`` for a parsed IDL file."""

    def __init__(self, spec, package="", extensibility="appendable"):
        self.spec = spec
        self.package = package
        self.extensibility = extensibility
        self.idl_name = os.path.basename(spec.path)
        self.file_module = dds_module_of_file(spec.path)
        self.includes = {}  # IDL file path -> variable of its module
        self.w = Writer()

    # -- names -----------------------------------------------------------

    def in_package(self, name):
        return self.package + "." + name if self.package else name

    def file_var(self, path):
        v = self.includes.get(path)
        if v is None:
            v = P + "f_" + dds_module_of_file(path)
            self.includes[path] = v
        return v

    def ref(self, node):
        """Expression for the Python object of a definition, here or in an
        included file."""
        if fe.inner_scope(node):
            raise fe.GeneratorError(
                "%s is defined inside %s, which DDS types cannot be"
                % (node.name, "::".join(fe.inner_scope(node))),
                node,
            )
        names = [py_name(m) for m in fe.enclosing_modules(node)] + [py_name(node.name)]
        if self.spec.is_main(node):
            return ".".join(names)
        fp = os.path.abspath(node.filepath)
        return self.file_var(fp) + "." + ".".join(names)

    # -- types -----------------------------------------------------------

    def type_expr(self, t, where):
        k = t.kind
        if k in PRIMITIVE:
            return P + "dds." + PRIMITIVE[k]
        if k in ("string", "wstring"):
            return "%sdds.%s(%s)" % (P, k, t.bound or "")
        if k == "sequence":
            if t.bound:
                return "%sdds.sequence(%s, %d)" % (P, self.type_expr(t.content, where), t.bound)
            return "%sdds.sequence(%s)" % (P, self.type_expr(t.content, where))
        if k == "array":
            dims = [t.length]
            content = t.content
            while content.kind == "array":
                dims.append(content.length)
                content = content.content
            return "%sdds.array(%s, %s)" % (
                P, self.type_expr(content, where), ", ".join(str(d) for d in dims))
        if k == "bitmask":
            return self.ref(t.node)
        if k == "named":
            n = t.node
            if fe.is_typedef(n) or fe.is_struct(n) or fe.is_union(n) or fe.is_enum(n) or fe.is_bitmask(n):
                if fe.is_forward(n):
                    raise fe.GeneratorError(
                        "%s is only declared: recursive types are not supported for DDS" % n.name,
                        where)
                return self.ref(n)
            raise fe.GeneratorError(
                "the %s %s has no form in DDS" % (fe.kind_name(n), n.name), where)
        raise fe.GeneratorError("%s has no form in DDS" % k, where)

    def literal(self, value, t):
        r = t.resolved()
        if r.kind == "named" and fe.is_enum(r.node):
            return "%s.%s" % (self.ref(r.node), py_name(value.name))
        if r.kind == "boolean":
            return "True" if value else "False"
        if r.kind in ("float", "double", "longdouble"):
            v = float(value)
            if v != v:
                return 'float("nan")'
            if v in (float("inf"), float("-inf")):
                return 'float("%s")' % ("inf" if v > 0 else "-inf")
            return repr(v)
        if r.kind == "fixed":
            raise fe.GeneratorError("fixed has no form in DDS", t.node)
        if isinstance(value, bool):
            return repr(int(value))
        return repr(value)

    # -- the file ----------------------------------------------------------

    def generate(self):
        body = Writer()
        self.w = body
        mods = []
        for it in fe.definitions(self.spec):
            for i in range(1, len(it.modules) + 1):
                if it.modules[:i] not in mods:
                    mods.append(it.modules[:i])
            self.definition(it.node)

        w = Writer()
        w(HEADER % self.idl_name)
        w('"""DDS types of %s, for rustorb_dds."""' % self.idl_name)
        w()
        w("import enum as %senum" % P)
        w("import types as %stypes" % P)
        w()
        w("import rustorb_dds as %sdds" % P)
        w()
        if self.includes:
            w("# Files included by %s" % self.idl_name)
            for path, var in self.includes.items():
                w("import %s as %s  # %s" % (
                    self.in_package(dds_module_of_file(path)), var, os.path.basename(path)))
            w()
        if mods:
            for m in mods:
                pyname = ".".join(py_name(x) for x in m)
                full = self.in_package(self.file_module) + "." + pyname
                w('%s = %stypes.ModuleType("%s")' % (pyname, P, full))
            w()
            w()
        w.lines.extend(body.lines)
        while w.lines and not w.lines[-1]:
            w.lines.pop()
        return w.text()

    def definition(self, node):
        if fe.is_module(node):
            return
        if fe.is_const(node):
            self.const(node)
        elif fe.is_enum(node):
            self.enum(node)
        elif fe.is_bitmask(node):
            self.bitmask(node)
        elif fe.is_typedef(node):
            self.typedef(node)
        elif fe.is_struct(node) and not fe.is_exception(node):
            if fe.is_forward(node):
                raise fe.GeneratorError(
                    "forward declarations (of %s) are not supported for DDS" % node.name, node)
            self.struct(node)
        elif fe.is_union(node):
            if fe.is_forward(node):
                raise fe.GeneratorError(
                    "forward declarations (of %s) are not supported for DDS" % node.name, node)
            self.union(node)
        # Interfaces, exceptions, valuetypes and natives have no DDS form;
        # they are left to the CORBA code.

    def assign(self, node, local):
        """``Module.Name = local`` for a definition in a module."""
        w = self.w
        ref = self.ref(node)
        if ref != local:
            w()
            w("%s = %s" % (ref, local))
            w("del %s" % local)
        w()
        w()

    def const(self, node):
        t = fe.type_of(node.type, node)
        w = self.w
        w("# const %s" % node.name)
        w("%s = %s" % (self.ref(node), self.literal(node.value, t)))
        w()

    def local_name(self, node):
        return py_name(node.name)

    def enum(self, node):
        w = self.w
        name = self.local_name(node)
        bits = fe.bit_bound(node, 32, 1, 32)
        args = ['"%s"' % "::".join(fe.scope_path(node))]
        if bits != 32:
            args.append("bit_bound=%d" % bits)
        ext = fe.extensibility(node, "final")
        if ext != "final":
            args.append('extensibility="%s"' % ext)
        default = [v.name for v in node.values if fe.annotation(v, "default_literal") is not None]
        if default:
            args.append('default_literal="%s"' % py_name(default[-1]))
        renamed = {py_name(v.name): v.name for v in node.values if py_name(v.name) != v.name}
        if renamed:
            args.append("names=%r" % renamed)
        w("@%sdds.enum(%s)" % (P, ", ".join(args)))
        w("class %s(%senum.IntEnum):" % (name, P))
        w.indent()
        for v in node.values:
            w("%s = %d" % (py_name(v.name), v.value))
        w.dedent()
        self.assign(node, name)

    def bitmask(self, node):
        w = self.w
        name = self.local_name(node)
        bits = node.bit_bound
        for v in node.values:
            if v.position >= bits:
                raise fe.GeneratorError(
                    "the position %d of %s is not below @bit_bound(%d)" % (v.position, v.name, bits),
                    node)
        args = ['"%s"' % "::".join(fe.scope_path(node))]
        if bits != 32:
            args.append("bit_bound=%d" % bits)
        ext = fe.extensibility(node, "final")
        if ext != "final":
            args.append('extensibility="%s"' % ext)
        renamed = {py_name(v.name): v.name for v in node.values if py_name(v.name) != v.name}
        if renamed:
            args.append("names=%r" % renamed)
        w("@%sdds.bitmask(%s)" % (P, ", ".join(args)))
        w("class %s(%senum.IntFlag):" % (name, P))
        w.indent()
        if not node.values:
            w("pass")
        for v in node.values:
            w("%s = 1 << %d" % (py_name(v.name), v.position))
        w.dedent()
        self.assign(node, name)

    def typedef(self, node):
        t = fe.type_of(node.type, node)
        w = self.w
        w("# typedef %s" % node.name)
        w('%s = %sdds.typedef("%s", %s)' % (
            self.ref(node), P, "::".join(fe.scope_path(node)), self.type_expr(t, node)))
        w()
        w()

    def type_args(self, node, ext):
        args = ['"%s"' % "::".join(fe.scope_path(node))]
        if ext != "final":
            args.append('extensibility="%s"' % ext)
        if fe.is_nested(node):
            args.append("nested=True")
        if fe.autoid(node) == "hash":
            args.append('autoid="hash"')
        return args

    def check_member(self, m):
        for a in NOT_YET:
            if fe.annotation(m, a) is not None:
                raise fe.GeneratorError(
                    "@%s (on %s) is not supported for DDS yet" % (a, m.name), m)
        if fe.annotation(m, "value") is not None:
            raise fe.GeneratorError("@value applies to enumerators, not to %s" % m.name, m)

    def member_extra(self, m, mid, auto):
        """The arguments of a member after its type: its ID when not the
        automatic one, ``@hashid`` and its name when it is not its Python
        name."""
        extra = []
        hashid = fe.annotation(m, "hashid")
        if hashid is not None:
            extra.append("hash_id=%r" % fe._string_arg(hashid))
        elif mid != auto:
            extra.append("id=%d" % mid)
        if py_name(m.name) != m.name:
            extra.append('name="%s"' % m.name)
        return extra

    def auto_ids(self, node, members, ids):
        """The IDs the members would get without ``@id``: what rustorb_dds
        computes, to know when to write the ID."""
        out = []
        prev = None
        hashed = fe.autoid(node) == "hash"
        for m, mid in zip(members, ids):
            if hashed:
                auto = fe.hashed_id(m.name)
            else:
                auto = 0 if prev is None else prev + 1
            out.append(auto)
            prev = mid
        return out

    def struct(self, node):
        w = self.w
        name = self.local_name(node)
        if getattr(node, "base", None) or getattr(node, "_base", None):
            raise fe.GeneratorError(
                "struct inheritance (of %s) is not supported for DDS yet" % node.name, node)
        ext = fe.extensibility(node, self.extensibility)
        members = list(node.members)
        ids = fe.member_ids(node, members)
        autos = self.auto_ids(node, members, ids)
        w("@%sdds.struct(%s)" % (P, ", ".join(self.type_args(node, ext))))
        w("class %s:" % name)
        w.indent()
        if not members:
            w("pass")
        for m, mid, auto in zip(members, ids, autos):
            self.check_member(m)
            t = fe.type_of(m.type, m)
            texpr = self.type_expr(t, m)
            key, opt = fe.is_key(m), fe.is_optional(m)
            if key and opt:
                raise fe.GeneratorError("%s cannot be both @key and @optional" % m.name, m)
            ext_ = fe.is_external(m)
            mu = fe.annotation(m, "must_understand") is not None and fe.must_understand(m) and not key
            extra = self.member_extra(m, mid, auto)
            if not (opt or ext_ or mu or extra):
                ann = ("%sdds.key(%s)" % (P, texpr)) if key else texpr
            else:
                args = [texpr] + extra
                for flag, on in (("key", key), ("optional", opt), ("must_understand", mu),
                                 ("external", ext_)):
                    if on:
                        args.append("%s=True" % flag)
                ann = "%sdds.member(%s)" % (P, ", ".join(args))
            w("%s: %s" % (py_name(m.name), ann))
        w.dedent()
        self.assign(node, name)

    def union(self, node):
        w = self.w
        name = self.local_name(node)
        ext = fe.extensibility(node, self.extensibility)
        if ext == "mutable":
            raise fe.GeneratorError(
                "mutable unions are not supported for DDS yet (union %s)" % node.name, node)
        disc = fe.type_of(node.discriminator_type, node)
        members = list(node.members)
        ids = fe.member_ids(node, members)
        autos = self.auto_ids(node, members, ids)
        args = [self.type_expr(disc, node)] + self.type_args(node, ext)
        w("@%sdds.union(%s)" % (P, ", ".join(args)))
        w("class %s:" % name)
        w.indent()
        for m, mid, auto in zip(members, ids, autos):
            self.check_member(m)
            if fe.is_optional(m) or fe.is_external(m) or fe.is_key(m):
                raise fe.GeneratorError(
                    "@optional, @external and @key are not supported on union members (%s)" % m.name,
                    m)
            t = fe.type_of(m.type, m)
            labels = [self.literal(l, disc) for l in m.labels]
            fn = "default_case" if m.is_default else "case"
            a = [self.type_expr(t, m)] + labels + self.member_extra(m, mid, auto)
            w("%s: %sdds.%s(%s)" % (py_name(m.name), P, fn, ", ".join(a)))
        w.dedent()
        self.assign(node, name)


def write_outputs(spec, outdir, package="", extensibility="appendable"):
    """Writes ``Foo_dds.py`` for ``spec`` under ``outdir`` (in the package
    ``package``); returns its path."""
    gen = PythonDds(spec, package, extensibility)
    text = gen.generate()
    top = outdir
    if package:
        for part in package.split("."):
            top = os.path.join(top, part)
            os.makedirs(top, exist_ok=True)
            init = os.path.join(top, "__init__.py")
            if not os.path.exists(init):
                with open(init, "w"):
                    pass
    path = os.path.join(top, gen.file_module + ".py")
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)
    return path
